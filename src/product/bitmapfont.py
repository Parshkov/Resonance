def rows(character: str) -> list[int]:
    """The 14 row bitmaps for one character."""
    hexrow = GLYPHS.get(ord(character), MISSING)
    return [int(hexrow[i:i + 2], 16) for i in range(0, len(hexrow), 2)]


def width(text: str, scale: int = 1) -> int:
    return len(text) * CELL_WIDTH * scale


def height(scale: int = 1) -> int:
    return CELL_HEIGHT * scale
